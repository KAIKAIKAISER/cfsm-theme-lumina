export function resolveLanguage(siteDefaultLang = 'auto') {
  const userPref = readStorage(STORAGE_KEYS.LANGUAGE)
  if (userPref === 'zh' || userPref === 'en') return userPref

  if (siteDefaultLang === 'zh' || siteDefaultLang === 'en') return siteDefaultLang

  if (typeof navigator !== 'undefined') {
    const navLang = String(navigator.language || '').toLowerCase()
    if (navLang.startsWith('zh')) return 'zh'
    return 'en'
  }
  return 'zh'
}

export function saveUserLanguage(lang) {
  writeStorage(STORAGE_KEYS.LANGUAGE, lang)
}
